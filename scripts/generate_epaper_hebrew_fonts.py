#!/usr/bin/env python3
"""Generate the Hebrew companion glyphs for the e-paper bitmap fonts.

The Latin fonts (generate_epaper_fonts.py) are rasterised with macOS CoreText and cover ASCII
only. This script adds the Hebrew letter block (U+05D0..U+05EA) for each Latin font size/weight,
rasterised from Heebo with Pillow/FreeType so it runs on any OS. The output uses the same
GlyphBitmap conventions (1-bit, row-major, tightly packed; bearings relative to the baseline),
so the renderer draws both scripts on one baseline.

Usage: python3 scripts/generate_epaper_hebrew_fonts.py
Requires: Pillow (pip install pillow).
"""

from __future__ import annotations

import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT_PATH = ROOT / "fonts" / "Heebo[wght].ttf"
OUT_CPP = ROOT / "components" / "epaper_ui" / "generated_epaper_hebrew_fonts.cpp"
OUT_H = ROOT / "components" / "epaper_ui" / "include" / "epaper_ui" / "generated_epaper_hebrew_fonts.h"

FIRST_CODEPOINT = 0x05D0  # alef
LAST_CODEPOINT = 0x05EA  # tav
# The 165px size is only used for large numerals, so it gets no Hebrew companion.
SIZES = [22, 26, 32, 38, 46, 55]
WEIGHTS = [("SemiBold", 600), ("Bold", 700), ("Black", 900)]


def render_glyph(font: ImageFont.FreeTypeFont, size: int, codepoint: int):
    char = chr(codepoint)
    pad = size
    canvas = Image.new("1", (size * 3, size * 3), 0)
    draw = ImageDraw.Draw(canvas)
    draw.fontmode = "1"  # no anti-aliasing: the panel is 1-bit
    baseline = size * 2
    draw.text((pad, baseline), char, fill=1, font=font, anchor="ls")
    advance = max(1, math.ceil(font.getlength(char)))
    bbox = canvas.getbbox()
    if bbox is None:
        return dict(width=0, height=0, bearing_x=0, bearing_y=0, advance=advance, bitmap=[])
    left, top, right, bottom = bbox
    width, height = right - left, bottom - top
    pixels = canvas.crop(bbox).load()
    packed, current, bits = [], 0, 0
    for row in range(height):
        for col in range(width):
            if pixels[col, row]:
                current |= 0x80 >> bits
            bits += 1
            if bits == 8:
                packed.append(current)
                current, bits = 0, 0
    if bits:
        packed.append(current)
    return dict(width=width, height=height, bearing_x=left - pad, bearing_y=baseline - top,
                advance=advance, bitmap=packed)


def emit_bytes(values: list[int]) -> str:
    lines = []
    for start in range(0, len(values), 16):
        lines.append("    " + ", ".join(f"0x{v:02X}" for v in values[start:start + 16]) + ",")
    return "\n".join(lines)


def main() -> None:
    count = LAST_CODEPOINT - FIRST_CODEPOINT + 1
    cpp = [
        "// Generated by scripts/generate_epaper_hebrew_fonts.py -- do not edit by hand.",
        '#include "epaper_ui/generated_epaper_hebrew_fonts.h"',
        "",
        '#include "epaper_ui/generated_epaper_fonts.h"',
        "",
        "namespace epaper_fonts {",
        "",
        "namespace {",
        "",
    ]
    table = []
    for size in SIZES:
        for weight_name, weight in WEIGHTS:
            font = ImageFont.truetype(str(FONT_PATH), size)
            font.set_variation_by_axes([weight])
            symbol = f"Hebrew{size}{weight_name}"
            glyphs, bitmap = [], []
            for codepoint in range(FIRST_CODEPOINT, LAST_CODEPOINT + 1):
                glyph = render_glyph(font, size, codepoint)
                glyphs.append((len(bitmap), glyph))
                bitmap.extend(glyph["bitmap"])
            cpp.append(f"const uint8_t k{symbol}Bitmaps[] = {{")
            cpp.append(emit_bytes(bitmap))
            cpp.append("};")
            cpp.append("")
            cpp.append(f"const epaper_font::GlyphBitmap k{symbol}Glyphs[] = {{")
            for offset, glyph in glyphs:
                cpp.append(
                    f"    {{{offset}, {len(glyph['bitmap'])}, {glyph['width']}, {glyph['height']}, "
                    f"{glyph['bearing_x']}, {glyph['bearing_y']}, {glyph['advance']}}},"
                )
            cpp.append("};")
            cpp.append("")
            table.append(
                f"    {{&kInter{size}{weight_name}, 0x{FIRST_CODEPOINT:04X}, {count}, "
                f"k{symbol}Glyphs, k{symbol}Bitmaps}},"
            )
    cpp += ["}  // namespace", "", "const epaper_font::ExtraGlyphRange kHebrewRanges[] = {"]
    cpp += table
    cpp += [
        "};",
        "",
        f"const size_t kHebrewRangeCount = {len(table)};",
        "",
        "}  // namespace epaper_fonts",
        "",
    ]
    OUT_CPP.write_text("\n".join(cpp))

    OUT_H.write_text(
        "\n".join(
            [
                "// Generated by scripts/generate_epaper_hebrew_fonts.py -- do not edit by hand.",
                "#ifndef GENERATED_EPAPER_HEBREW_FONTS_H",
                "#define GENERATED_EPAPER_HEBREW_FONTS_H",
                "",
                "#include <cstddef>",
                "",
                '#include "epaper_ui/bitmap_font.h"',
                "",
                "namespace epaper_fonts {",
                "",
                "// One entry per Latin font that has a Hebrew companion (same pixel size and weight).",
                "extern const epaper_font::ExtraGlyphRange kHebrewRanges[];",
                "extern const size_t kHebrewRangeCount;",
                "",
                "}  // namespace epaper_fonts",
                "",
                "#endif  // GENERATED_EPAPER_HEBREW_FONTS_H",
                "",
            ]
        )
    )
    print(f"wrote {OUT_CPP.relative_to(ROOT)} and {OUT_H.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
